package start.loop;

public class While2_1 {
    public static void main(String[] args){
        int sum = 0;
        int num = 10;

        sum = sum + num;
        System.out.println(sum);

        num++;
        sum = sum + num;
        System.out.println(sum);

        num++;
        sum = sum + num;
        System.out.println(sum);
    }
}
